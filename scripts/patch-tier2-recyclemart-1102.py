def row(t):
    return f"<tr><td><strong>{t[0]}</strong></td><td>{t[1]}</td><td>{t[2]}</td><td>{t[3]}</td></tr>"


def py(t):
    return "(" + ", ".join(f'"{x}"' for x in t) + ")"


tot_pages = 0
for pref, (name, loc, new) in FIX.items():
    old = (name, loc, "店頭", "地元密着")
    n = 0
    for f in sorted(glob.glob(f"app/tier2/{pref}/*/page.tsx")):
        s = open(f, encoding="utf-8").read()
        if row(old) in s:
            s = s.replace(row(old), "" if new is None else row(new))
            open(f, "w", encoding="utf-8").write(s)
            n += 1
    tot_pages += n
    print(pref, "removed" if new is None else "renamed", n)
print("pages changed", tot_pages)

