def md_to_html(text):
    text = re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', text)
    normalized = text.replace('\\n', '\n')
    if re.search(r'\b1\.\s', normalized):
        m = re.search(r'(.*?)\b1\.\s+(.+)$', normalized, re.DOTALL)
        if m:
            intro = m.group(1).strip()
            rest = m.group(2)
            items_split = re.split(r'\s+(\d+)\.\s+', rest)
            items = [items_split[0].strip()]
            i = 1
            while i + 1 < len(items_split):
                items.append(items_split[i + 1].strip())
                i += 2
            items = [it for it in items if it]
            if len(items) >= 2:
                items_html = ''.join(f'<li>{item}</li>' for item in items)
                if intro:
                    return f'<p>{intro}</p><ol>{items_html}</ol>'
                return f'<ol>{items_html}</ol>'
    if '\n' in normalized:
        paragraphs = normalized.split('\n\n')
        out = []
        for p in paragraphs:
            p = p.strip().replace('\n', '<br/>')
            if p:
                out.append(f'<p>{p}</p>')
        return ''.join(out)
    return f'<p>{normalized}</p>'


def fmt(n):
    n = int(n)
    if n >= 10_000_000:
        return f"{n//10000:,}万円"
    if n >= 1_000_000:
        return f"{n//10000}万円"
    return f"{n:,}円"


def market_basis(b):
    """このボトルの相場基準額(円)とYahoo落札件数、十分性フラグを返す。
    yahoo中央値(180日)を優先。件数20未満や欠損は reference_price にフォールバック。"""
    m = (b.get("yahoo_median_jpy_180d") or "").strip()
    n = (b.get("yahoo_sample_n") or "0").strip()
    sample = int(n) if n.isdigit() else 0
    if m.isdigit() and int(m) > 0 and sample >= 20:
        return int(m), sample, True
    rp = (b.get("reference_price_jpy_2026_05") or "0").strip()
    return (int(rp) if rp.isdigit() else 0), sample, False


def yen_range(median, lo_pct, hi_pct):
    """相場×割合(%)の円レンジ文字列。10円単位に丸め。"""
    a = int(round(median * lo_pct / 100.0, -1))
    z = int(round(median * hi_pct / 100.0, -1))
    if a > z:
        a, z = z, a
    return f"約{a:,}〜{z:,}円"


def yen_pct(median, pct):
    v = int(round(median * pct / 100.0, -1))
    return f"約{v:,}円"


