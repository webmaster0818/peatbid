PH = re.compile(r"\{[^{}]+\}")


def esc(s: str) -> str:
    """JSON-LD 内の表記（json.dumps の ensure_ascii）に合わせる"""
    return json.dumps(s, ensure_ascii=True)[1:-1]


def compile_pair(old: str, new: str, escaped: bool):
    """旧テンプレを正規表現に、新テンプレを置換関数に変換"""
    toks = PH.findall(old)
    for t in PH.findall(new):
        assert t in toks, f"新テンプレにだけあるプレースホルダ: {t} in {new[:40]}"
    parts = PH.split(old)
    names = {}
    rx = ""
    for i, lit in enumerate(parts):
        rx += re.escape(esc(lit) if escaped else lit)
        if i < len(toks):
            t = toks[i]
            if t in names:
                rx += f"(?P={names[t]})"
            else:
                names[t] = f"g{len(names)}"
                # 値は空にならない（+?）。文をまたがないよう「。」を越えさせない（地域の特徴 demand だけは文を含む）。
                # 先頭のプレースホルダは直前の文まで食わないよう「、」「？」も越えさせず、文頭（。、？" > の直後）から始める。
                stops = ["。"] if t not in ("{p['demand']}", '{be.get("collectibility_note", "")}') else []
                lead = i == 0 and lit == ""
                if lead:
                    stops += ["、", "？"]
                if escaped:
                    tok = r'(?:\\u[0-9a-fA-F]{4}|[^\\\n<>"])'  # \uXXXX を1文字として扱う（途中から始めない）
                    neg = "|".join(re.escape(esc(c)) for c in stops)
                    cls = f"(?:(?!{neg}){tok})" if stops else tok
                    pre = "(?:" + "|".join(f"(?<={re.escape(esc(c))})" for c in ["。", "、", "？"]) + '|(?<=")|(?<=>))' if lead else ""
                else:
                    cls = '[^\\n<>"' + "".join(stops) + ']'
                    pre = '(?<=[。、？">])' if lead else ""
                rx += f"{pre}(?P<{names[t]}>{cls}+?)"
    rx_c = re.compile(rx)
    lits = [esc(x) if escaped else x for x in parts]
    key = max(lits, key=len)
    nparts = PH.split(new)
    ntoks = PH.findall(new)

    def repl(m):
        out = ""
        for i, lit in enumerate(nparts):
            out += esc(lit) if escaped else lit
            if i < len(ntoks):
                out += m.group(names[ntoks[i]])
        return out

    return rx_c, repl, key


